#!/bin/bash
# Re-generates the C++ from the .dsp files (run after editing a .dsp). Needs /opt/homebrew/bin/faust.
cd "$(dirname "$0")"
for n in jf_reverb jf_drive; do
  /opt/homebrew/bin/faust -lang cpp -a arch.cpp -cn ${n}_dsp -scn FaustDsp -single -ftz 0 $n.dsp -o $n.h || exit 1
  sed -i '' "1s|^|// Generated by Faust $(/opt/homebrew/bin/faust --version | head -1 | awk '{print $3}') from $n.dsp (faust -lang cpp -a arch.cpp -cn ${n}_dsp -scn FaustDsp -single -ftz 0). Do not edit.\n#pragma once\n#include \"faust_min.h\"\n|" $n.h
done
