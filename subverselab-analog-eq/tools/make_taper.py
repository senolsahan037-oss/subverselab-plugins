#!/usr/bin/env python3
"""Writes Source/Ge1100Taper.h: for every band, the slide-pot position for each panel mark from -12 to +12 dB in 0.5 dB
steps. Rule: the panel's ±12 ends are the pot's physical ends (the circuit gives about +12.5 / -12.9 dB there); a mark L
in between is the position where the band's own centre gain, all other sliders at 0, is L/12 of that end's gain. The gain
is computed on the analog model of the traced circuit (tools/ge_statespace.py). Independent of the sample rate.

  make_taper.py      rewrites ../Source/Ge1100Taper.h and prints the end gains
"""
import os
import numpy as np
from scipy.optimize import brentq
import ge_statespace as g

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Source", "Ge1100Taper.h")
MARKS = np.arange(-12.0, 12.0001, 0.5)

def centre_gain(band, x):
    pos = [0.5] * 12; pos[band] = x
    flat = 20 * np.log10(abs(g.analog_response([0.5] * 12, [g.LABELS[band]])[0]))
    return 20 * np.log10(abs(g.analog_response(pos, [g.LABELS[band]])[0])) - flat

rows, ends = [], []
for b in range(12):
    gb, gc = centre_gain(b, 0.0), centre_gain(b, 1.0)          # boost end (N), cut end (MID)
    ends.append((gb, gc))
    row = []
    for L in MARKS:
        if L == 0: row.append(0.5); continue
        target = L / 12 * (gb if L > 0 else -gc)   # -gc > 0, so a negative mark gives a negative target
        lo, hi = (0.0, 0.5) if L > 0 else (0.5, 1.0)
        if abs(L) == 12: row.append(lo if L > 0 else hi); continue
        row.append(brentq(lambda x: centre_gain(b, x) - target, lo, hi, xtol=1e-9))
    rows.append(row)
    print(f"band {g.LABELS[b]:>5} Hz: end gains {gb:+.2f} / {gc:+.2f} dB; position at +6 {row[list(MARKS).index(6.0)]:.4f}, at -6 {row[list(MARKS).index(-6.0)]:.4f}")

with open(OUT, "w") as f:
    f.write("// Generated by tools/make_taper.py from the analog model of the traced circuit. Do not edit by hand.\n")
    f.write("// kTaper[band][k]: slide-pot position (0 = N end, full boost; 0.5 = centre tap; 1 = MID end, full cut) for the panel\n")
    f.write("// mark -12 + 0.5 k dB. The ±12 marks are the pot's ends; a mark in between gives L/12 of that end's centre gain.\n")
    f.write("#pragma once\n#include <array>\n\nnamespace ge\n{\n")
    f.write(f"constexpr int kMarks = {len(MARKS)};\n")
    f.write("constexpr std::array<std::array<double, kMarks>, 12> kTaper { {\n")
    for b, row in enumerate(rows):
        f.write("    { " + ", ".join(f"{v:.9f}" for v in row) + (" },\n" if b < 11 else " } } };\n"))
    f.write("constexpr std::array<std::array<double, 2>, 12> kEndGainDb { {\n")
    f.write(",\n".join(f"    {{ {gb:.4f}, {gc:.4f} }}" for gb, gc in ends) + " } };\n")
    f.write("\n// panel mark (dB, -12 ... +12) -> slide-pot position, linear between the 0.5 dB rows\n")
    f.write("inline double positionForMark (int band, double markDb)\n{\n")
    f.write("    const double k = (std::min (12.0, std::max (-12.0, markDb)) + 12.0) * 2.0;\n")
    f.write("    const int i = std::min (kMarks - 2, (int) k);\n    const double t = k - i;\n")
    f.write("    return kTaper[(size_t) band][(size_t) i] * (1 - t) + kTaper[(size_t) band][(size_t) (i + 1)] * t;\n}\n} // namespace ge\n")
print("wrote", OUT)
